// Generated-message matching; all display templates are kept with the language catalogs.
export function translatePattern(
  normalized: string,
  translate: (value: string) => string,
): string | undefined {
  const patterns: [RegExp, (...args: string[]) => string][] = [
    [/^(\d+) containers · ([\d.,\s]+) items$/, (_, a, b) => `${a} sandık · ${b} eşya`],
    [/^(\d+) stacks$/, (_, n) => `${n} eşya yığını`],
    [
      /^(\d+) measurable goals · (\d+) Companion-only goals$/,
      (_, a, b) => `${a} ölçülebilir hedef · ${b} yalnızca Companion’da kalan hedef`,
    ],
    [/^(\d+) design-only placements$/, (_, n) => `${n} yalnızca tasarımda kullanılabilen yerleşim`],
    [/^(\d+) planned placements$/, (_, n) => `${n} planlanan yerleşim`],
    [
      /^(\d+) placements applied in game\. Review your farm before saving\.$/,
      (_, n) => `Oyuna ${n} yerleşim uygulandı. Kaydetmeden önce çiftliğini kontrol et.`,
    ],
    [
      /^(\d+) goals confirmed by live game data\. Save confirmation updates after the next game save\.$/,
      (_, n) =>
        `${n} hedef canlı oyun verisinden doğrulandı. Kalıcı kayıt doğrulaması, oyunun sonraki kaydından sonra güncellenir.`,
    ],
    [
      /^Occupied tile: (\d+), (\d+)\. Nothing was cleared\.$/,
      (_, x, y) => `${x}, ${y} karesi dolu. Hiçbir şey silinmedi.`,
    ],
    [/^Saved base level: (.+)$/, (_, n) => `Kayıtlı temel seviye: ${translate(n)}`],
    [
      /^Effective Fishing level (\d+) is required\.$/,
      (_, n) => `Etkili Balıkçılık seviyesinin en az ${n} olması gerekir.`,
    ],
    [/^(\d+)\+ \(buffs can count\)$/, (_, n) => `${n}+ (geçici güçlendirmeler sayılabilir)`],
    [
      /^Talk to (.+) and choose a gift they love\.$/,
      (_, name) => `${name} ile konuş ve çok sevdiği bir hediye seç.`,
    ],
    [
      /^Perfection’s friendship target is (\d+) hearts for ([^.!?]+)\.$/,
      (_, n, name) => `Mükemmellik için ${name} ile ${n} kalbe ulaşmalısın.`,
    ],
    [
      /^(\d+) hearts · letter delivered after the requirement is reached\.$/,
      (_, n) => `${n} kalp; koşula ulaşıldıktan sonra tarif mektupla gelir.`,
    ],
    [/^(\d+) scheduled stops$/, (_, n) => `${n} program durağı`],
    [/^Difficulty (\d+)$/, (_, n) => `Zorluk: ${n}`],
    [/^Birthday in (\d+) days$/, (_, n) => `Doğum gününe ${n} gün var`],
    [/^(spring|summer|fall|winter) (\d+)$/i, (_, s, d) => `${translate(s)} ${d}`],
    [
      /^(spring|summer|fall|winter) reference\.$/i,
      (_, s) => `${translate(s.charAt(0).toUpperCase() + s.slice(1).toLowerCase())} haritası.`,
    ],
    [/^(\d+) hearts$/, (_, n) => `${n} kalp`],
    [/^(\d+) goals in your planner$/, (_, n) => `Planlayıcında ${n} hedef var`],
    [/^Last synced ([\d/:.,\sAPM]+)\.$/, (_, date) => `Son güncelleme: ${date}.`],
    [/^Last saved (.+)$/, (_, date) => `Son kayıt: ${date}`],
    [/^Last disk save (.+)$/, (_, date) => `Diskteki son kayıt: ${date}`],
    [
      /^Saved date: ((?:Spring|Summer|Fall|Winter) \d+, Year \d+)\.$/,
      (_, date) => `Kayıtlı tarih: ${translate(date)}.`,
    ],
    [/^(\d+) days remain after the saved day\.$/, (_, n) => `Kayıtlı günden sonra ${n} gün kaldı.`],
    [/^(\d+) official entries$/, (_, n) => `${n} resmî başarım`],
    [/^verified (\d{4}-\d{2}-\d{2})\.$/, (_, date) => `doğrulama: ${date}.`],
    [/^(\d+) collection entries for 1\.6\.$/, (_, n) => `1.6 sürümü için ${n} koleksiyon kaydı.`],
    [/^(.+) \(\+1 day\)$/, (_, time) => `${time} (+1 gün)`],
    [/^Mines floor (\d+)$/, (_, n) => `Madenler, ${n}. kat`],
    [
      /^Reach floor (\d+) and cast into its (water|lava) pool\.$/,
      (_, n, kind) => `${n}. kata ulaş ve ${kind === 'lava' ? 'lav' : 'su'} havuzuna olta at.`,
    ],
    [/^(\d+) confirmed goals$/, (_, n) => `${n} doğrulanan hedef`],
    [
      /^(\d+) existing game notes · (\d+) pending Planner notes$/,
      (_, existing, pending) => `Oyunda ${existing} not · Planlayıcıda ${pending} bekleyen not`,
    ],
    [/^Baby (.+)$/, (_, name) => `Yavru ${translate(name)}`],
    [/^appearance (\d+)$/, (_, n) => `${n}. görünüm`],
    [/^Checked (\d{4}-\d{2}-\d{2})$/, (_, date) => `Kontrol: ${date}`],
    [/^Source unavailable: (.+)$/, (_, id) => `Kaynak bulunamadı: ${id}`],
    [/^Priority for (.+)$/, (_, name) => `${name} için öncelik`],
    [/^Manually mark (.+)$/, (_, name) => `${name}: elle işaretle`],
    [/^Unmark (.+)$/, (_, name) => `${name}: işareti kaldır`],
    [/^Pin (.+)$/, (_, name) => `${name}: sabitle`],
    [/^Remove (.+)$/, (_, name) => `${name}: kaldır`],
    [
      /^Stardew Valley Wiki(?: · (.+))?$/,
      (_, title) => `Stardew Valley Wiki${title ? ' · ' + translate(title) : ''}`,
    ],
    [
      /^Year (\d+)(?:–(\d+))?( or later)?$/,
      (_, min, max, more) => `${min}${max ? '–' + max : ''}. yıl${more ? ' veya sonrası' : ''}`,
    ],
    [
      /^(.+): ([\d.]+) hearts(?:–([\d.]+))?( or more)?$/,
      (_, name, min, max, more) =>
        `${name}: ${min}${max ? '–' + max : ''} kalp${more ? ' veya üzeri' : ''}`,
    ],
    [/^(.+): at least ([\d.]+) hearts$/, (_, name, n) => `${name}: en az ${n} kalp`],
    [/^Season: (.+)$/, (_, s) => `Mevsim: ${s.split(' / ').map(translate).join(' / ')}`],
    [/^Day: (.+)$/, (_, s) => `Gün: ${s.replace(/even/g, 'çift').replace(/odd/g, 'tek')}`],
    [/^Seen event: ([^·]+)$/, (_, ids) => `Görülen etkinlik: ${ids}`],
    [/^Learn recipe: (.+)$/, (_, name) => `Tarifi öğren: ${translate(name)}`],
    [/^House upgrade: (.+)$/, (_, n) => `Ev yükseltmesi: ${n.replace('or more', 'veya üzeri')}`],
    [/^Saved statistic (.+): (.+) or more$/, (_, id, n) => `Kayıtlı sayaç ${id}: ${n} veya üzeri`],
    [/^Profession: (.+)$/, (_, id) => `Meslek: ${id}`],
    [/^In-game achievement: (.+)$/, (_, id) => `Oyun içi başarım: ${id}`],
    [/^World progression: (.+)$/, (_, id) => `Dünya ilerlemesi: ${id}`],
    [/^Except: (.+)$/, (_, s) => `Şu koşul hariç: ${translate(s)}`],
    [
      /^(Any|All): (.+)$/,
      (_, scope, s) => `${scope === 'Any' ? 'Herhangi biri' : 'Hepsi'}: ${translate(s)}`,
    ],
    [/^Time: (.+)$/, (_, s) => `Saat: ${s}`],
    [/^Weather: (.+)$/, (_, s) => `Hava: ${s.split(' / ').map(translate).join(' / ')}`],
    [/^Requires (.+)$/, (_, s) => `Gerekli koşul: ${translate(s)}`],
    [/^Planting condition: (.+)$/, (_, s) => `Ekim koşulu: ${translate(s)}`],
    [
      /^(spring|summer|fall|winter) (\d+), Year (\d+)$/i,
      (_, s, d, y) => `${translate(s)} ${d}, ${y}. yıl`,
    ],
    [/^(.+) has its own rhythm\.$/, (_, s) => `${translate(s)} kendine özgü bir ritme sahiptir.`],
    [/^Only days (.+)$/, (_, s) => `Yalnızca şu günler: ${s}`],
    [/^(\d+) day\(s\) remaining\.$/, (_, n) => `${n} gün kaldı.`],
    [/^(\d+) items$/, (_, n) => `${n} eşya`],
    [/^(\d+) portraits$/, (_, n) => `${n} portre`],
    [/^(\d+) dishes cooked$/, (_, n) => `${n} yemek pişirildi`],
    [
      /^Browse installed quest references \((\d+)\)$/,
      (_, n) => `Oyundaki görev referanslarına göz at (${n})`,
    ],
    [
      /^Produces (\d+)\. Read from this game installation; recipe learning and completion are checked separately against your save\.$/,
      (_, n) =>
        `${n} adet üretir. Kurulu oyundan okunur; tarif bilgisi ile üretim eylemi kayıttan ayrı kontrol edilir.`,
    ],
    [
      /^(\d+) matching collection entries · dates, weather, equipment and access still apply\.$/,
      (_, n) =>
        `${n} eşleşen koleksiyon kaydı; tarih, hava, ekipman ve erişim koşulları geçerlidir.`,
    ],
    [/^(\d+) notes$/, (_, n) => `${n} not`],
    [/^(\d+) selected$/, (_, n) => `${n} seçildi`],
    [/^(\d+) festivals$/, (_, n) => `${n} festival`],
    [/^Backup: (.+)$/, (_, n) => `Yedek: ${n}`],
    [
      /^(\d+) forage rules · (\d+) fish rules$/,
      (_, a, b) => `${a} toplama kuralı · ${b} balık kuralı`,
    ],
    [/^(\d+) scheduled stops$/, (_, n) => `${n} program durağı`],
    [/^(\d+) locations$/, (_, n) => `${n} konum`],
    [/^(\d+) exit tiles$/, (_, n) => `${n} çıkış karesi`],
    [/^(\d+) × (\d+) tiles$/, (_, x, y) => `${x} × ${y} kare`],
    [/^Destination: (.+)\.$/, (_, p) => `Hedef: ${p}.`],
    [/^Start: (.+)\.$/, (_, p) => `Başlangıç: ${p}.`],
    [/^Tile (.+)\.$/, (_, p) => `Kare ${p}.`],
    [/^Tile (\d+), (\d+)$/, (_, x, y) => `Kare ${x}, ${y}`],
    [/^Next move: (.+)$/, (_, t) => `Sonraki hareket: ${t}`],
    [
      /^Festival on this date: (.+)\. Normal daily schedules may be replaced\.$/,
      (_, n) =>
        `Bu tarihte festival var: ${n}. Normal programın yerini festival programı alabilir.`,
    ],
    [/^(\d+) hearts or more$/, (_, n) => `En az ${n} kalp`],
    [/^Plan filtered missing \((\d+)\)$/, (_, n) => `Listedeki eksikleri planla (${n})`],
    [/^(\d+)% OF OFFICIAL PERFECTION$/, (_, n) => `RESMİ MÜKEMMELLİĞİN %${n} KISMI`],
    [/^(\d+)% maximum contribution$/, (_, n) => `En fazla %${n} katkı`],
    [/^(\d+) farm plans$/, (_, n) => `${n} çiftlik planı`],
    [/^House upgrade: (.+)$/, (_, n) => `Ev yükseltmesi: ${translate(n)}`],
    [/^Learn recipe: (.+)$/, (_, n) => `Tarifi öğren: ${translate(n)}`],
    [/^Profession: (.+)$/, (_, n) => `Meslek: ${n}`],
    [/^In-game achievement: (.+)$/, (_, n) => `Oyun içi başarım: ${n}`],
    [/^World progression: (.+)$/, (_, n) => `Dünya ilerlemesi: ${n}`],
    [/^Spouse: (.+)$/, (_, n) => `Eş: ${n}`],
    [/^Find (.+) in this location$/, (_, n) => `Bu konumda ${n} karakterini bul`],
    [
      /^Saved statistic (.+): (\d+) or more$/,
      (_, n, count) => `Kayıtlı istatistik ${n}: en az ${count}`,
    ],
    [/^(\d+) items$/, (_, n) => `${n} eşya`],
    [/^(\d+) portraits$/, (_, n) => `${n} portre`],
    [/^(\d+) monster sheets$/, (_, n) => `${n} canavar görseli`],
    [
      /^Avoid detected saved obstacles \((\d+)\)$/,
      (_, n) => `Kayıtta tespit edilen engellerden kaçın (${n})`,
    ],
    [
      /^Stardrop Tea: \+(\d+) friendship points for this occasion; it does not consume the normal gift limit\.$/,
      (_, n) =>
        `Yıldızkaydı Çayı: bu hediye zamanında +${n} arkadaşlık puanı verir; normal hediye sınırını tüketmez.`,
    ],
    [/^Verify stock: (.+)$/, (_, s) => `${translate(s)} stokunu kontrol et`],
    [/^(\d+) from planned production$/, (_, n) => `Planlanan üretimden ${n}`],
    [/^([+-]?\d+) base friendship points$/, (_, n) => `${n} temel arkadaşlık puanı`],
    [
      /^(\d+) hearts · (.+) · (Seen|Not recorded as seen|Unknown)$/,
      (_, n, l, s) => `${n} kalp · ${translate(l)} · ${translate(s)}`,
    ],
    [/^(.+): (\d+(?:\.\d+)?) hearts or more$/, (_, n, h) => `${n}: en az ${h} kalp`],
    [/^Season: (.+)$/, (_, s) => `Mevsim: ${s.split(' / ').map(translate).join(' / ')}`],
    [/^Year (\d+) or later$/, (_, n) => `${n}. yıl veya sonrası`],
    [/^Time: (.+)$/, (_, s) => `Saat: ${s}`],
    [/^Weather: (.+)$/, (_, s) => `Hava: ${translate(s)}`],
    [/^Except: (.+)$/, (_, s) => `Hariç: ${translate(s)}`],
    [/^Letter \/ progression: ([^·]+)$/, (_, s) => `Mektup / ilerleme işareti: ${s}`],
    [/^(.+) · Floors (.+)$/, (_, l, n) => `${translate(l)} · ${n}. katlar`],
    [
      /^Choose (\d+) remaining offering\(s\) to plan\.$/,
      (_, n) => `Planlamak için kalan bağışlardan ${n} tanesini seç.`,
    ],
    [/^One batch produces (\d+)\.$/, (_, n) => `Bir üretimde ${n} adet elde edilir.`],
    [
      /^Reach (\d+) hearts with (.+); read the recipe letter delivered the following day\.$/,
      (_, h, n) => `${n} ile ${h} kalbe ulaş; ertesi gün gelen tarif mektubunu oku.`,
    ],
    [
      /^Reach (\w+) level (\d+); claim the recipe on the level-up screen\.$/,
      (_, s, n) =>
        `${translate(s)} becerisinde ${n}. seviyeye ulaş ve seviye atlama ekranından tarifi al.`,
    ],
    [
      /^The Queen of Sauce: year (\d+), (\w+) (\d+)\.$/,
      (_, y, s, d) => `Sosların Kraliçesi: ${y}. yıl, ${translate(s)} ${d}.`,
    ],
    [/^Shop offers: (.+)\.$/, (_, s) => `Dükkân teklifleri: ${s}`],
    [/^Forage routes: (.+)\.$/, (_, s) => `Toplama bölgeleri: ${s}`],
    [
      /^Possible monster drops: (.+)\.$/,
      (_, s) => `Düşürebilen canavarlar: ${s.split(' · ').map(translate).join(' · ')}`,
    ],
    [/^Process in (.+): (.+)\.$/, (_, m, s) => `${translate(m)} ile işle: ${s}`],
    [
      /^(.+); (\d+) produced per batch\.$/,
      (_, s, n) => `${translate(s)}; bir üretimde ${n} adet elde edilir.`,
    ],
    [/^(\d+) × (.+): (.+)$/, (_, n, s, a) => `${n} × ${translate(s)}: ${translate(a)}`],
    [
      /^([\d.,]+)g remains in the lifetime earnings record\.$/,
      (_, n) => `Toplam kazanç hedefi için ${n}g kaldı.`,
    ],
    [/^Earn a total of ([\d.,]+)g on this farm\.$/, (_, n) => `Bu çiftlikte toplam ${n}g kazan.`],
    [
      /^Complete (\d+) distinct (cooking|crafting|fishing) collection entries\.$/,
      (_, n, s) => `${translate(s)} koleksiyonundaki farklı kayıtlardan ${n} tanesini tamamla.`,
    ],
    [
      /^Grow (.+) in (.+)\. First harvest: (\d+) days(; regrows every (\d+) days)?\.$/,
      (_, s, seasons, d, _reg, r) =>
        `${translate(s)} yetiştir. Mevsimler: ${seasons.split(' / ').map(translate).join(' / ')}. İlk hasat: ${d} gün${r ? `; yeniden hasat: ${r} gün` : ''}.`,
    ],
    [/^Welcome back, (.+)\.$/, (_, name) => `Tekrar hoş geldin, ${name}.`],
    [/^(\d+) \/ (\d+) hearts · ([\d.,]+) points$/, (_, a, b, n) => `${a} / ${b} kalp · ${n} puan`],
    [/^Next heart: (\d+) \/ 250 points$/, (_, n) => `Sonraki kalp: ${n} / 250 puan`],
    [/^(\d+) in this farmer’s bag$/, (_, n) => `Bu çiftçinin çantasında ${n}`],
    [/^Day (\d+)$/, (_, n) => `${n}. gün`],
    [/^(\d+) days$/, (_, n) => `${n} gün`],
    [/^(\d+) watered days$/, (_, n) => `${n} sulanan gün`],
    [/^Page (\d+) of (\d+)$/, (_, a, b) => `Sayfa ${a} / ${b}`],
    [/^(\d+) tracked goals$/, (_, n) => `${n} hedef izleniyor`],
    [/^Catch (.+)$/, (_, s) => `${translate(s)} yakala`],
    [/^Cook (.+)$/, (_, s) => `${translate(s)} pişir`],
    [/^Craft (.+)$/, (_, s) => `${translate(s)} üret`],
    [/^Ship (.+)$/, (_, s) => `${translate(s)} gönder`],
    [/^Learn (.+)$/, (_, s) => `${translate(s)} tarifini öğren`],
    [/^Gather (\d+) (.+)$/, (_, n, s) => `${n} ${translate(s)} topla`],
  ];
  for (const [pattern, replacement] of patterns)
    if (pattern.test(normalized))
      return normalized.replace(pattern, (...args) => replacement(...args));
}
